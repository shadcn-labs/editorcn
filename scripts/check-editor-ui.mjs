import { readFileSync, existsSync, readdirSync } from "node:fs";
import { resolve, relative } from "node:path";

const __dirname = import.meta.dirname;
const root = resolve(__dirname, "..");

const read = (relativePath) =>
  readFileSync(resolve(root, relativePath), "utf-8");

const failures = [];
const checks = [];

const check = (label, condition) => {
  if (condition) {
    checks.push(label);
    return;
  }
  failures.push(label);
};

const componentPath = (name) =>
  `packages/editor-ui/src/components/${name}/${name}.tsx`;

// Behavioural contracts recorded in docs/DECISIONS.md. These are the two
// invariants that consumers of the registry depend on, so they fail loudly.
const popover = read(componentPath("popover"));
check(
  "popover keeps initialFocus={false} (D4: no focus steal on open)",
  popover.includes("initialFocus={false}")
);
check(
  "popover keeps finalFocus={false} (D4: focus is not yanked on close)",
  popover.includes("finalFocus={false}")
);

const separator = read(componentPath("separator"));
check(
  "separator keeps horizontal orientation selectors (D8)",
  separator.includes("data-[orientation=horizontal]:h-px") &&
    separator.includes("data-[orientation=horizontal]:w-full")
);
check(
  "separator keeps vertical orientation selectors (D8)",
  separator.includes("data-[orientation=vertical]:w-px") &&
    separator.includes("data-[orientation=vertical]:self-stretch")
);

// Every component an item flattens must exist in that same item, otherwise
// the installed project has an import pointing at a file it never received.
const items = [
  "editor",
  "block-editor",
  "static-renderer",
  "image-placeholder",
  "table",
];

const ANIMATION_UTILITY =
  /\b(?:animate-in|animate-out|slide-in-from-|slide-out-to-|zoom-in-|zoom-out-|fade-in-|fade-out-)\b/;

for (const item of items) {
  const json = read(`apps/web/public/r/${item}.json`);
  const targets = new Set(
    [...json.matchAll(/"target":\s*"@components\/([^"]+)"/g)].map(
      (match) => match[1]
    )
  );
  const contents = [...json.matchAll(/"content":\s*"((?:[^"\\]|\\.)*)"/g)].map(
    (match) => JSON.parse(`"${match[1]}"`)
  );

  const referenced = new Set(
    [...json.matchAll(/@components\/editor-ui\/([a-z-]+)\.tsx/g)].map(
      (match) => match[1]
    )
  );
  for (const name of referenced) {
    check(
      `${item}: @components/editor-ui/${name}.tsx is shipped in the same item`,
      targets.has(`editor-ui/${name}.tsx`)
    );
  }

  check(
    `${item}: registry item carries meta.version`,
    /"meta":\s*\{[^}]*"version"/.test(json)
  );

  const animated = contents.some((content) => ANIMATION_UTILITY.test(content));
  check(
    animated
      ? `${item}: declares tw-animate-css (it ships animated components)`
      : `${item}: no animation utilities, tw-animate-css not required`,
    !animated || /"tw-animate-css@\^1\.4\.0"/.test(json)
  );
}

// Every stylesheet that ships animated components must carry the motion tokens
// the components read. They are generated by scripts/sync-styles.mjs, so a
// hand edit inside the markers is drift, not a local override.
const styleSheets = [
  "packages/editor/src/style.css",
  "packages/block-editor/src/style.css",
  "packages/extensions/src/image-placeholder/style.css",
  "packages/extensions/src/table/style.css",
];

for (const sheet of styleSheets) {
  const css = read(sheet);
  check(
    `${sheet}: declares the motion tokens`,
    css.includes("--editor-motion-duration-base")
  );
  check(
    `${sheet}: honours prefers-reduced-motion`,
    css.includes("@media (prefers-reduced-motion: reduce)")
  );
  check(
    `${sheet}: motion block is generated (markers present)`,
    css.includes("/* editor-motion:start */") &&
      css.includes("/* editor-motion:end */")
  );
}

for (const sheet of [
  "packages/editor/src/style.css",
  "packages/block-editor/src/style.css",
]) {
  check(
    `${sheet}: syntax theme is generated (markers present)`,
    read(sheet).includes("/* editor-syntax:start */") &&
      read(sheet).includes("/* editor-syntax:end */")
  );
  check(
    `${sheet}: no __CONTENT_ROOT__ placeholder left unsubstituted`,
    !read(sheet).includes("__CONTENT_ROOT__")
  );
}

// npm consumers get a compiled bundle. The package is private and unpublished,
// so any surviving import of it is a runtime module-not-found after install.
for (const pkg of ["editor", "block-editor"]) {
  const manifest = JSON.parse(read(`packages/${pkg}/package.json`));
  check(
    `${pkg}: @editorcn/editor-ui is not a published dependency`,
    !("dependencies" in manifest) ||
      !Object.keys(manifest.dependencies).includes("@editorcn/editor-ui")
  );
  check(
    `${pkg}: @editorcn/editor-ui is a devDependency so tsup bundles it`,
    Boolean(manifest.devDependencies?.["@editorcn/editor-ui"])
  );

  const dist = `packages/${pkg}/dist/index.js`;
  if (!existsSync(resolve(root, dist))) {
    checks.push(`${pkg}: dist not built, skipped bundle check`);
    continue;
  }
  const bundle = read(dist);
  check(
    `${pkg}: dist has no @editorcn/editor-ui import (Phase A regression guard)`,
    !bundle.includes("@editorcn/editor-ui")
  );
  check(
    `${pkg}: dist inlines the editor-ui primitives`,
    bundle.includes('"data-slot"') || bundle.includes("data-slot")
  );
}

// A consumer-relative import is only valid if the registry actually delivers the
// file it names. The registry flattens per feature, so an item may legitimately
// reference a file another item ships (`extensions/core/*`) — the check is against
// the union of every target, not the single item. This is the guard that catches
// a deleted source file still being advertised in a code sample.
const shipped = new Set();
const sources = [];

for (const item of items) {
  const json = read(`apps/web/public/r/${item}.json`);
  for (const match of json.matchAll(/"target":\s*"(@components\/[^"]+)"/g)) {
    shipped.add(match[1].replace("@components/", "@/components/"));
  }
  for (const match of json.matchAll(
    /"content":\s*"((?:[^"\\]|\\.)*)"/g
  )) {
    sources.push([item, JSON.parse(`"${match[1]}"`)]);
  }
}

// Owned by the consumer's own project, never by the registry.
const CONSUMER_OWNED = /^@\/(?:lib|app)\//;
const CONSUMER_IMPORT = /(?:from\s+|import\s+)["'](@\/[^"']+)["']/g;

const resolvable = (specifier) =>
  CONSUMER_OWNED.test(specifier) ||
  [specifier, `${specifier}.ts`, `${specifier}.tsx`, `${specifier}/index.ts`]
    .map((candidate) => shipped.has(candidate))
    .some(Boolean);

const seen = new Set();
const checkImport = (where, specifier) => {
  const label = `${where}: ${specifier} resolves to a file the registry ships`;
  if (seen.has(label)) {
    return;
  }
  seen.add(label);
  check(label, resolvable(specifier));
};

for (const [item, content] of sources) {
  for (const [, specifier] of content.matchAll(CONSUMER_IMPORT)) {
    checkImport(item, specifier);
  }
}

// The docs teach these import paths, so a stale one is a broken copy-paste.
const docFiles = readdirSync(resolve(root, "apps/web/content/docs"), {
  recursive: true,
  withFileTypes: true,
})
  .filter((entry) => entry.isFile() && entry.name.endsWith(".mdx"))
  .map((entry) =>
    relative(root, resolve(entry.parentPath, entry.name)).replaceAll("\\", "/")
  );

// A route file mixes its own working imports with the code samples it renders in
// backticks, so only the template literals are held to the registry's contract.
for (const route of [
  "apps/web/src/app/(app)/(root)/page.tsx",
  "apps/web/src/app/(app)/block-editor/page.tsx",
]) {
  for (const [, sample] of read(route).matchAll(/`([^`]*)`/g)) {
    for (const [, specifier] of sample.matchAll(CONSUMER_IMPORT)) {
      checkImport(route, specifier);
    }
  }
}

for (const docFile of docFiles) {
  for (const [, specifier] of read(docFile).matchAll(CONSUMER_IMPORT)) {
    checkImport(docFile, specifier);
  }
}

for (const label of checks) {
  console.log(`  ok  ${label}`);
}

if (failures.length > 0) {
  console.error(`\n${failures.length} editor-ui check(s) failed:`);
  for (const label of failures) {
    console.error(`  FAIL  ${label}`);
  }
  process.exit(1);
}

console.log(`\n${checks.length} editor-ui checks passed.`);
